/* ================= CURSOR BLACK HOLE (experimental — off by default, toggled in Settings) =====
   Rebuilt on real WebGL shader distortion instead of CSS approximations, adapted from a working
   Three.js reference. A fullscreen plane sits fixed behind all real page content (z-index: -1,
   pointer-events: none — it never intercepts clicks or covers anything), textured with a
   procedurally-drawn gradient matching this site's own color theme (not an external photo), and
   a fragment shader pulls that texture's UV coordinates toward the cursor with inverse-distance
   falloff — genuine pixel displacement, GPU-side, not a blur trick. WebGL itself has excellent
   cross-browser support (better than the SVG-filter approach this replaces), so this actually
   satisfies "every browser" more robustly than the CSS-only version did.
   Three.js (~150KB) is only ever fetched via dynamic import() when the effect is switched on —
   pages never pay for it while the toggle is off. The pull strength eases from near-zero while
   the mouse is moving up to a stronger value once it's been stationary for a beat, so the warp
   visibly builds rather than snapping to full strength — same "grows when idle" behavior asked
   for originally, just driven by the shader's own uniform instead of CSS opacity. */
const CURSOR_WARP_KEY = 'mrwestcoin_blackhole_enabled';
function cursorWarpEnabled(){ return localStorage.getItem(CURSOR_WARP_KEY) === 'true'; }

let cwActive = false, cwMouseX = -9999, cwMouseY = -9999, cwIdle = false, cwIdleTimer = null;
let cwVoidEl = null, cwFullEl = null, cwRenderer = null, cwRAF = null, cwForce = 0.015;

function cwBuildThemeTexture(THREE){
  // a small offscreen canvas gradient using this site's own palette, used as the WebGL plane's
  // texture — matches the page's real background instead of an unrelated stock photo. Made
  // noticeably higher-contrast than the first version: a near-flat gradient still technically
  // gets distorted by the shader, but the distortion is invisible if there's nothing with edges
  // or contrast for the eye to see actually bending — a grid + brighter, thicker accent lines
  // gives the warp something real to visibly grab onto.
  const c = document.createElement('canvas');
  c.width = 512; c.height = 512;
  const ctx = c.getContext('2d');
  const g = ctx.createRadialGradient(256, 180, 20, 256, 256, 380);
  g.addColorStop(0, '#332920');
  g.addColorStop(0.55, '#1a1510');
  g.addColorStop(1, '#0a0705');
  ctx.fillStyle = g; ctx.fillRect(0, 0, 512, 512);
  // a visible grid — evenly-spaced high-contrast lines make bending obvious in a way a few
  // random faint streaks don't
  ctx.strokeStyle = 'rgba(217,122,63,0.4)';
  ctx.lineWidth = 1.5;
  for(let i = 0; i <= 512; i += 32){
    ctx.beginPath(); ctx.moveTo(i, 0); ctx.lineTo(i, 512); ctx.stroke();
    ctx.beginPath(); ctx.moveTo(0, i); ctx.lineTo(512, i); ctx.stroke();
  }
  // brighter accent streaks on top of the grid for extra visible detail
  ctx.strokeStyle = 'rgba(244,236,216,0.25)';
  for(let i = 0; i < 10; i++){
    ctx.lineWidth = 2 + (i % 3);
    ctx.beginPath();
    ctx.moveTo(Math.random() * 512, 0);
    ctx.lineTo(Math.random() * 512, 512);
    ctx.stroke();
  }
  return new THREE.CanvasTexture(c);
}

async function setupCursorWarp(){
  if(cwActive) return; // already running
  const skip = window.matchMedia && (
    window.matchMedia('(pointer: coarse)').matches ||
    window.matchMedia('(prefers-reduced-motion: reduce)').matches
  );
  if(skip) return;

  try{
    // Everything that can plausibly fail — the network fetch of Three.js AND WebGL context
    // creation itself — now lives inside this one try block. Previously only the import() call
    // was guarded; a WebGL context failure (unsupported browser, GPU blocklist, etc.) happening
    // right after a successful import would have thrown unhandled and silently done nothing,
    // which is exactly the kind of failure that looks like "doesn't work" with zero clue why.
    const THREE = await import('https://esm.sh/three@0.133.0/build/three.module.js');
    if(!cursorWarpEnabled()) return; // setting may have been switched off again while the import was loading

    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(75, window.innerWidth / window.innerHeight, 1, 2000);
    camera.position.z = 5;
    cwRenderer = new THREE.WebGLRenderer({ alpha: true });
    cwRenderer.setPixelRatio(window.devicePixelRatio || 1); // crisp on Retina/high-DPI displays
    cwRenderer.setSize(window.innerWidth, window.innerHeight);
    const canvasEl = cwRenderer.domElement;
    canvasEl.id = 'cursorWarpCanvas';
    document.body.appendChild(canvasEl);

    const distortionMaterial = new THREE.ShaderMaterial({
      uniforms: {
        u_mouse: { value: new THREE.Vector2(-9999, -9999) },
        u_resolution: { value: new THREE.Vector2(window.innerWidth, window.innerHeight) },
        u_texture: { value: cwBuildThemeTexture(THREE) },
        u_force: { value: 0 },
    },
    vertexShader: `
      varying vec2 vUv;
      void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0); }
    `,
    fragmentShader: `
      uniform vec2 u_mouse, u_resolution;
      uniform sampler2D u_texture;
      uniform float u_force;
      varying vec2 vUv;
      void main(){
        vec2 st = vUv;
        vec2 mouse = u_mouse / u_resolution;
        mouse.y = 1.0 - mouse.y;
        float aspect = u_resolution.x / u_resolution.y;
        vec2 scaledSt = st * vec2(aspect, 1.0);
        float dist = distance(scaledSt, mouse * vec2(aspect, 1.0));
        float distortion = u_force / max(dist, 0.02); // clamped so it can't blow up right at the cursor
        vec2 distortedUv = st + (mouse - st) * distortion;
        gl_FragColor = texture2D(u_texture, clamp(distortedUv, 0.0, 1.0));
      }
    `
  });
  const aspectRatio = window.innerWidth / window.innerHeight;
  const size = 7.65 * 1.15; // small safety margin over the exact frustum-fill math, so the
                             // plane can't fall short of covering every corner of the viewport
  const geometry = new THREE.PlaneGeometry(size * aspectRatio, size);
  const mesh = new THREE.Mesh(geometry, distortionMaterial);
  scene.add(mesh);

  cwVoidEl = document.createElement('div');
  cwVoidEl.id = 'cursorWarpVoid';
  document.body.appendChild(cwVoidEl);

  // Foreground distortion — a SINGLE element that always covers the entire page exactly
  // (top:0/left:0/right:0/bottom:0, never resized or repositioned), so it's structurally
  // impossible for it to end up "confined to an area." The cursor-tracking part is done
  // entirely differently from before: instead of moving a small circle around (which is what
  // kept ending up mispositioned), this element's mask-image is a radial gradient whose CENTER
  // moves via a CSS custom property. The element's own box never changes; only which part of
  // its full-page backdrop-filter is actually visible does. That backdrop-filter is what
  // genuinely distorts real text/buttons wherever the visible part of the mask currently is —
  // not the decorative WebGL background, which stays as the separate ambient effect behind it.
  cwFullEl = document.createElement('div');
  cwFullEl.id = 'cursorWarpFull';
  document.body.appendChild(cwFullEl);

  cwActive = true;

  const onResize = () => {
    cwRenderer.setSize(window.innerWidth, window.innerHeight);
    distortionMaterial.uniforms.u_resolution.value.set(window.innerWidth, window.innerHeight);
  };
  window.addEventListener('resize', onResize);

  const onMove = (e) => {
    cwMouseX = e.clientX; cwMouseY = e.clientY;
    cwVoidEl.style.left = cwMouseX + 'px';
    cwVoidEl.style.top = cwMouseY + 'px';
    cwFullEl.style.setProperty('--cw-x', cwMouseX + 'px');
    cwFullEl.style.setProperty('--cw-y', cwMouseY + 'px');
    cwVoidEl.classList.remove('idle'); // matches the earlier "invisible while moving" behavior —
                                        // this got dropped by accident in the WebGL rewrite
    cwFullEl.classList.remove('idle');
    cwIdle = false;
    clearTimeout(cwIdleTimer);
    cwIdleTimer = setTimeout(() => {
      cwIdle = true;
      cwVoidEl.classList.add('idle');
      cwFullEl.classList.add('idle');
    }, 450);
  };
  document.addEventListener('mousemove', onMove);

  function tick(){
    if(!cwActive) return;
    // eases toward the target force rather than snapping — this is the "smoothly increases
    // when idle" behavior, now driven by the shader itself
    const target = cwIdle ? 0.16 : 0.015;
    cwForce += (target - cwForce) * 0.06;
    distortionMaterial.uniforms.u_force.value = cwForce;
    distortionMaterial.uniforms.u_mouse.value.set(cwMouseX, cwMouseY);
    cwRenderer.render(scene, camera);
    cwRAF = requestAnimationFrame(tick);
  }
  tick();

  cwTeardown = () => {
    cwActive = false;
    clearTimeout(cwIdleTimer);
    if(cwRAF) cancelAnimationFrame(cwRAF);
    document.removeEventListener('mousemove', onMove);
    window.removeEventListener('resize', onResize);
    canvasEl.remove();
    if(cwVoidEl){ cwVoidEl.remove(); cwVoidEl = null; }
    if(cwFullEl){ cwFullEl.remove(); cwFullEl = null; }
    cwRenderer.dispose();
    cwRenderer = null;
  };
  } catch(e){
    // visible in devtools instead of silently doing nothing — the previous version's silent
    // catch is exactly what made a real failure indistinguishable from "not implemented"
    console.warn('[cursor black hole] WebGL setup failed, falling back to a simpler CSS-only version:', e);
    setupCursorWarpFallback();
  }
}

