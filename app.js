// Runs on EVERY page (not just Settings) — this is what keeps the signed-in account active as
// you navigate between separate pages, since each page load re-establishes Firebase's
// (persisted) auth session from scratch. Wrapped in try/catch because this is a single script —
// an uncaught error ANYWHERE in it (e.g. Firebase failing to load — a blocked CDN request, an ad
// blocker, a flaky network) would otherwise silently kill every line of code still to come,
// including the entire Element Clicker and the minigames grid defined further down this file.
try{
  if(FIREBASE_CONFIGURED){
    firebase.auth().onAuthStateChanged((user) => {
      if(user){
      // ALWAYS keep investorId synced to the real Firebase Auth UID — anonymous session or not.
      // This matters because Firebase security rules check auth.uid against the data being
      // written (e.g. a marketplace listing's sellerId, or the players/{id} key itself). Using a
      // separately locally-generated ID for anonymous sessions meant those writes could be
      // silently rejected by the rules — the .catch(()=>{}) on every write swallows the error, so
      // it looked like nothing happened rather than showing a failure.
      if(investorId !== user.uid){
        const oldLocalId = investorId;
        switchActiveAccount(user.uid);
        // if there's existing progress saved under the old locally-generated ID (from before
        // this fix, or from earlier in this same session before Firebase responded), carry it
        // over to the real UID instead of silently losing it
        if(oldLocalId && oldLocalId !== user.uid && db){
          migrateLocalIdDataTo(oldLocalId, user.uid);
        }
      }
    } else {
      // Genuinely no session — NOT "we haven't checked yet." Firebase guarantees this callback's
      // FIRST call already reflects any persisted session restored from storage, so it's only
      // safe to create a brand new anonymous identity here, inside the callback. Checking
      // firebase.auth().currentUser synchronously right after registering this listener (the old
      // code) is a race condition: that restore hasn't finished yet, so currentUser reads null
      // almost every time even when a real persisted session exists — which meant a fresh
      // anonymous identity got created on EVERY page load, abandoning all progress (tools,
      // elements, everything) tied to the previous one. That was the actual cause of things
      // "disappearing" when navigating between pages.
      firebase.auth().signInAnonymously().catch(() => {});
    }
    updateAuthUI(user);
    });
  }
} catch(e){
  console.error('[firebase-auth] setup failed — continuing without account sync so the rest of the site (minigames, Element Clicker, etc.) still works:', e);
}

async function migrateLocalIdDataTo(oldId, newId){
  try{
    const oldSnap = await db.ref('players/' + oldId).once('value');
    const oldData = oldSnap.val();
    if(oldData){
      const newSnap = await db.ref('players/' + newId).once('value');
      if(!newSnap.val()){ // never clobber progress that already exists under the real UID
        const { inbox: _ignoredInbox, ...carry } = oldData;               // players can't write their own inbox (see database.rules.json)
        await db.ref('players/' + newId).update(carry);
        portfolio = migratePortfolio(oldData);
        markSynced(oldData);
        persistLocal();
        refreshEconomyUI();
      }
      await db.ref('players/' + oldId).remove().catch(() => {}); // clean up the now-orphaned old record
    }
  } catch(e){ /* best-effort one-time migration — never worth blocking on */ }
}

